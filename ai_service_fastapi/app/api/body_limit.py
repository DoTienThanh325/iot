"""Bound v2 JSON bytes before request parsing/NumPy allocation."""
import json


class BodyLimitMiddleware:
    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http" or scope["path"] != "/api/v2/analyze":
            return await self.app(scope, receive, send)
        runtime = getattr(scope["app"].state, "runtime", None)
        limit = runtime["config"].max_body_bytes if runtime else 4_000_000
        size, chunks = 0, []
        while True:
            message = await receive()
            if message["type"] == "http.disconnect":
                return
            chunk = message.get("body", b"")
            size += len(chunk)
            if size > limit:
                body = json.dumps({"detail": "Request body exceeds configured byte limit"}).encode()
                await send({"type": "http.response.start", "status": 413,
                            "headers": [(b"content-type", b"application/json")]})
                await send({"type": "http.response.body", "body": body})
                return
            chunks.append(chunk)
            if not message.get("more_body", False):
                break
        delivered = False

        async def replay():
            nonlocal delivered
            if not delivered:
                delivered = True
                return {"type": "http.request", "body": b"".join(chunks), "more_body": False}
            return await receive()

        await self.app(scope, replay, send)
